#!/usr/bin/env python3
"""Build bundled synonym senses from the official WordNet 3.0 database archive.
Usage: python3 scripts/build-thesaurus.py /path/to/WNdb-3.0.tar.gz
Download: https://wordnetcode.princeton.edu/3.0/WNdb-3.0.tar.gz
Only reads data members; never extracts archive paths or downloads at runtime.
"""
import hashlib
import json
from pathlib import Path
import re
import sys
import tarfile

archive = Path(sys.argv[1])
output = Path(__file__).resolve().parents[1] / 'Sources/TersoAnalysis/Resources/WordNet'
output.mkdir(parents=True, exist_ok=True)
senses = []
with tarfile.open(archive) as source:
    for pos in ('noun', 'verb', 'adj', 'adv'):
        lines = source.extractfile(f'dict/data.{pos}').read().decode('utf-8').splitlines()
        if pos == 'noun':
            license_text = '\n'.join(re.sub(r'^\s+\d+ ?', '', line).rstrip() for line in lines if line.startswith('  '))
            (output / 'LICENSE.txt').write_text(license_text + '\n')
        for line in lines:
            if not line or not line[0].isdigit():
                continue
            data, gloss = line.split('|', 1)
            fields = data.split()
            count = int(fields[3], 16)
            words = list(dict.fromkeys(re.sub(r'\((?:a|p|ip)\)$', '', fields[4 + 2*i]).replace('_', ' ') for i in range(count)))
            if len(words) < 2:
                continue
            senses.append(dict(id=pos + fields[0], partOfSpeech={'adj': 'adjective', 'adv': 'adverb'}.get(pos, pos), definition=gloss.strip(), words=words))
(output / 'synonyms.json').write_text(json.dumps(senses, ensure_ascii=False, separators=(',', ':')) + '\n')
(output / 'SOURCE.txt').write_text('WordNet 3.0, Princeton University (2006).\nhttps://wordnet.princeton.edu/\nhttps://wordnetcode.princeton.edu/3.0/WNdb-3.0.tar.gz\nArchive SHA-256: ' + hashlib.sha256(archive.read_bytes()).hexdigest() + '\nGenerated with scripts/build-thesaurus.py; only synsets with alternative words retained.\nDefinitions and examples are supplied by WordNet, not generated by Terso.\n')
print(f'{len(senses)} synonym senses; {(output / "synonyms.json").stat().st_size:,} bytes')
